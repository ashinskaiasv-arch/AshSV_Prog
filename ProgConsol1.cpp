bool UserInput(string input) {
    if (input.empty()) return false;

    try {
        size_t pos;
        stoi(input, &pos);
        return pos == input.length();
    }
    catch (...) {
        return false;
    }
}

void task1() {
    // Задание 1. Вычислить расстояние между двумя точками с координатами (х1, у1) и (х2, у2).
    // Координаты точек вводятся с клавиатуры.
    double x1, y1, x2, y2;

    cout << "Введите координаты первой точки (x1 y1): ";
    cin >> x1 >> y1;
    cout << "Введите координаты второй точки (x2 y2): ";
    cin >> x2 >> y2;

    double distance = sqrt(pow(x2 - x1, 2) + pow(y2 - y1, 2));

    cout << "Расстояние между точками = " << distance << endl;
}

void task2() {
    // Задание 2. С клавиатуры вводится четырехзначное число. Найти сумму его цифр.
    int number;

    cout << "Введите четырехзначное число: ";
    cin >> number;

    // Проверка, что число действительно четырехзначное
    if (number < 1000 || number > 9999) {
        cout << "Ошибка! Введите четырехзначное число (от 1000 до 9999)." << endl;
        return;
    }

    // Находим сумму цифр
    int sum = 0;
    int temp = number;

    sum += temp % 10;        // последняя цифра
    temp /= 10;
    sum += temp % 10;        // третья цифра
    temp /= 10;
    sum += temp % 10;        // вторая цифра
    temp /= 10;
    sum += temp;             // первая цифра

    cout << "Сумма цифр числа " << number << " = " << sum << endl;
}

void task3() {
    // Задание 3. Вводятся три произвольных числа x, y, z. Найти наибольшее среди них.
    double x, y, z;

    cout << "Введите x: ";
    cin >> x;

    cout << "Введите y: ";
    cin >> y;

    cout << "Введите z: ";
    cin >> z;

    // Поиск наибольшего числа
    if ((x > y) && (x > z)) {
        cout << "Число x является наибольшим: " << x << endl;
    }
    else if ((y > x) && (y > z)) {
        cout << "Число y является наибольшим: " << y << endl;
    }
    else if ((z > x) && (z > y)) {
        cout << "Число z является наибольшим: " << z << endl;
    }
    else {
        cout << "Все числа равны или есть несколько наибольших." << endl;
        cout << "x = " << x << ", y = " << y << ", z = " << z << endl;
    }
}

void task4() {
    // Задание 4. Даны действительные положительные числа x, y, z.
    // Выяснить существует ли треугольник с длинами сторон x, y, z.
    // Если треугольник существует, то ответить – является ли он равнобедренным.

    double x, y, z;

    // Ввод данных
    cout << "Введите длину стороны x: ";
    cin >> x;

    cout << "Введите длину стороны y: ";
    cin >> y;

    cout << "Введите длину стороны z: ";
    cin >> z;

    // Проверка на положительность сторон
    if (x <= 0 || y <= 0 || z <= 0) {
        cout << "Ошибка: Длины сторон должны быть положительными числами!" << endl;
        return;
    }

    // Проверка существования треугольника
    // Треугольник существует, если сумма любых двух сторон больше третьей
    if ((x + y > z) && (x + z > y) && (y + z > x)) {
        cout << "Треугольник со сторонами " << x << ", " << y << ", " << z << " существует." << endl;

        // Проверка на равнобедренность
        if (x == y || x == z || y == z) {
            cout << "Этот треугольник является равнобедренным." << endl;

            // Дополнительная проверка на равносторонний треугольник
            if (x == y && y == z) {
                cout << "Это также равносторонний треугольник (частный случай равнобедренного)." << endl;
            }
        }
        else {
            cout << "Этот треугольник не является равнобедренным." << endl;
        }
    }
    else {
        cout << "Треугольник со сторонами " << x << ", " << y << ", " << z << " НЕ существует!" << endl;
        cout << "Нарушено неравенство треугольника." << endl;
    }
}

