//Задача 4. Дано целое число n (1 <= n <= 99), определяющее возраст человека (в годах). Для 
//этого числа напечатать фразу «мне n лет», учитывая, что при некоторых значениях n слово 
//«лет» надо заменить на слово «год» или «года».

#include <iostream>

int main() {
    int n;
    
    std::cout << "Введите возраст (от 1 до 99): ";
    std::cin >> n;
    
    // Проверяем корректность ввода
    if (n < 1 || n > 99) {
        std::cout << "Ошибка: возраст должен быть от 1 до 99" << std::endl;
        return 1;
    }
    
    // Определяем последнюю цифру и исключения для 11-14
    int lastDigit = n % 10;
    bool isTeenException = (n % 100 >= 11) && (n % 100 <= 14);
    
    // Выбираем правильное слово с помощью тернарных операторов
    std::string word = isTeenException ? "лет" :
                       (lastDigit == 1) ? "год" :
                       (lastDigit >= 2 && lastDigit <= 4) ? "года" : "лет";
    
    // Выводим результат
    std::cout << "мне " << n << " " << word << std::endl;
    
    return 0;
}