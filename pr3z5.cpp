//Задание 5. Найти сумму делителей каждого из целых чисел от 50 до 70 
#include <iostream>
using namespace std;

int main() {
    // Перебираем числа от 50 до 70
    for (int n = 50; n <= 70; n++) {
        int sum = 0; // Инициализируем сумму делителей для текущего числа

        // Находим все делители числа n и суммируем их
        for (int i = 1; i <= n; i++) {
            if (n % i == 0) { // Если i — делитель числа n (остаток от деления равен 0)
                sum += i; // Добавляем делитель к сумме
            }
        }

        // Выводим результат для текущего числа
        cout << "Число " << n << ": сумма делителей = " << sum << endl;
    }

    return 0;
}
