//Задача 2. Даны две тройки вещественных чисел. В каждой тройке все числа различные. 
//Найти среднее арифметическое средних чисел каждой тройки (средним назовем такое число в тройке, которое больше наименьшего из чисел данной тройки, но меньше наибольшего).

#include <iostream>

int main() {
    double a1, b1, c1;  // первая тройка
    double a2, b2, c2;  // вторая тройка
    
    std::cout << "Введите первую тройку чисел (через пробел): ";
    std::cin >> a1 >> b1 >> c1;
    
    std::cout << "Введите вторую тройку чисел (через пробел): ";
    std::cin >> a2 >> b2 >> c2;
    
    // Находим среднее число в первой тройке
    // Используем тернарные операторы для нахождения min, max и среднего
    double min1 = (a1 < b1) ? ((a1 < c1) ? a1 : c1) : ((b1 < c1) ? b1 : c1);
    double max1 = (a1 > b1) ? ((a1 > c1) ? a1 : c1) : ((b1 > c1) ? b1 : c1);
    double middle1 = (a1 != min1 && a1 != max1) ? a1 : ((b1 != min1 && b1 != max1) ? b1 : c1);
    
    // Находим среднее число во второй тройке
    double min2 = (a2 < b2) ? ((a2 < c2) ? a2 : c2) : ((b2 < c2) ? b2 : c2);
    double max2 = (a2 > b2) ? ((a2 > c2) ? a2 : c2) : ((b2 > c2) ? b2 : c2);
    double middle2 = (a2 != min2 && a2 != max2) ? a2 : ((b2 != min2 && b2 != max2) ? b2 : c2);
    
    // Находим среднее арифметическое средних чисел
    double average = (middle1 + middle2) / 2.0;
    
    std::cout << "Среднее число в первой тройке: " << middle1 << std::endl;
    std::cout << "Среднее число во второй тройке: " << middle2 << std::endl;
    std::cout << "Среднее арифметическое средних чисел: " << average << std::endl;
    
    return 0;
}