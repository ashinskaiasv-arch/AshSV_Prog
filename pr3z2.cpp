//Задание 2. Вывести на экран последовательность из n чисел Фибоначчи (1 1 2 3 5 8 
//13…). Решить задачу с помощью цикла for (без использования рекурсии). Сделать проверку на корректность ввода количества чисел. 

#include <iostream>
using namespace std;

int main() {
    int n;

    // Проверка корректности ввода
    do {
        cout << "Введите количество чисел Фибоначчи (положительное целое число): ";
        cin >> n;

        if (cin.fail() || n <= 0) {
            cout << "Ошибка! Пожалуйста, введите положительное целое число.\n";
            cin.clear(); // сбрасываем флаг ошибки
            cin.ignore(10000, '\n'); // очищаем буфер ввода
        }
    } while (n <= 0);

    cout << "Последовательность Фибоначчи из " << n << " чисел:\n";

    // Переменные для хранения двух предыдущих чисел Фибоначчи
    long long prev1 = 1, prev2 = 1;
    long long current;

    // Вывод последовательности с помощью цикла for
    for (int i = 1; i <= n; ++i) {
        if (i == 1 || i == 2) {
            current = 1;
        } else {
            current = prev1 + prev2;
            prev2 = prev1;
            prev1 = current;
        }

        cout << current;
        if (i < n) {
            cout << " ";
        }
    }
    cout << endl;

    return 0;
}
