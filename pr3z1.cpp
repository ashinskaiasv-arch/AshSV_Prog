//Задание 1. Написать программу для нахождения минимального из десяти произвольных
//чисел, вводимых с клавиатуры. Решить задачу с помощью цикла while или
//do...while

#include <iostream>
using namespace std;

int main() {
    int number;          // переменная для хранения текущего введённого числа
    int minNumber;       // переменная для хранения минимального числа
    int count = 0;     // счётчик введённых чисел

    cout << "Введите 10 произвольных чисел:" << endl;

    do {
        cout << "Число " << count + 1 << ": ";
        cin >> number;

        // Инициализируем minNumber первым введённым числом
        if (count == 0) {
            minNumber = number;
        }
        // Сравниваем текущее число с минимальным и обновляем при необходимости
        else if (number < minNumber) {
            minNumber = number;
        }

        count++;  // увеличиваем счётчик
    } while (count < 10);  // продолжаем, пока не введём 10 чисел

    cout << "Минимальное число из введённых: " << minNumber << endl;

    return 0;
}
