//Дано натуральное число n. Вычислить...

#include <iostream>
using namespace std;

int main() {
    int n, a;
    double sum = 0.0; // Для хранения суммы с плавающей точкой
    cout << "Введите натуральное число n: ";
    cin >> n;

    // Проверка на корректность ввода (n должно быть натуральным числом)
    if (n <= 0) {
        cout << "Ошибка: n должно быть натуральным числом (n > 0)!" << endl;
        return 1;
    }

    cout << "Введите значение a: ";
    cin >> a;

    // Вычисляем сумму ряда с помощью цикла for
    for (int i = 0; i < n; ++i) {
        double denominator = 1; // Знаменатель дроби

        // Формируем знаменатель: a(a+1)(a+2)...(a+i)
        for (int j = 0; j <= i; ++j) {
            denominator *= (a + j);
        }

        // Добавляем слагаемое 1 / знаменатель к сумме
        sum += 1.0 / denominator;
    }

    cout << "Сумма ряда: " << sum << endl;
    return 0;
}

